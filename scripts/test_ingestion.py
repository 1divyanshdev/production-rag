import os
import sys
from pathlib import Path

# Add project root to python path
ROOT_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT_DIR))

import pymupdf
from backend.app.services.ingestion_service import DocumentIngestionService


def create_sample_pdf(filepath: str):
    """Creates a sample multi-page PDF dynamically for testing ingestion."""
    doc = pymupdf.open()

    # Page 1
    page1 = doc.new_page()
    page1.insert_text(
        (50, 50),
        "Production RAG Platform - Architecture Overview\n\n"
        "Page 1: Introduction\n"
        "Retrieval-Augmented Generation (RAG) combines search systems with generative LLMs "
        "to deliver accurate, grounded responses based on user-provided documentation.",
        fontsize=12
    )

    # Page 2
    page2 = doc.new_page()
    page2.insert_text(
        (50, 50),
        "Page 2: Ingestion & Vector Storage\n"
        "Document ingestion extracts clean text streams and page-level metadata. "
        "The text is later split into semantic chunks and indexed into Qdrant vector database.",
        fontsize=12
    )

    # Page 3
    page3 = doc.new_page()
    page3.insert_text(
        (50, 50),
        "Page 3: Citation & Grounding\n"
        "By maintaining strict page numbers during chunking, the RAG platform produces "
        "precise source citations for every answer generated by the LLM.",
        fontsize=12
    )

    doc.save(filepath)
    doc.close()
    print(f"Sample PDF created successfully at: {filepath}")


def main():
    sample_pdf_path = ROOT_DIR / "sample_doc.pdf"
    
    try:
        # Step 1: Create test PDF
        create_sample_pdf(str(sample_pdf_path))

        # Step 2: Test Document Ingestion Service
        service = DocumentIngestionService()
        documents = service.ingest_pdf(
            file_source=str(sample_pdf_path),
            custom_metadata={"author": "Dev Team", "category": "Documentation"}
        )

        print("\n" + "=" * 60)
        print(f"INGESTION SUCCESSFUL - Extracted {len(documents)} Page Documents")
        print("=" * 60 + "\n")

        for idx, doc in enumerate(documents, start=1):
            print(f"--- Document Page {idx} ---")
            print(f"Content:\n{doc.page_content}\n")
            print(f"Metadata:")
            print(f"  - Document ID:    {doc.metadata.document_id}")
            print(f"  - Filename:       {doc.metadata.filename}")
            print(f"  - Page Number:    {doc.metadata.page_number} / {doc.metadata.total_pages}")
            print(f"  - SHA-256 Hash:   {doc.metadata.file_hash[:16]}...")
            print(f"  - File Size:      {doc.metadata.file_size_bytes} bytes")
            print(f"  - Created At:     {doc.metadata.created_at}")
            print(f"  - Extra Metadata: {doc.metadata.extra}")
            print("-" * 50 + "\n")

    finally:
        # Clean up sample file
        if sample_pdf_path.exists():
            os.remove(sample_pdf_path)
            print("Sample PDF cleaned up.")


if __name__ == "__main__":
    main()
